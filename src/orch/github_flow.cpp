GithubFlow::GithubFlow(store::RunStore& store, Dispatcher& dispatcher,
                       git::Repository& repository, GithubFlowConfig config)
    : store_(store),
      dispatcher_(dispatcher),
      repository_(repository),
      config_(std::move(config)) {}

Status GithubFlow::ensure_push(std::string_view run_id,
                               std::string_view milestone_id,
                               const std::string& branch, const std::string& ref,
                               store::UnixTime now) {
  auto commit = repository_.head_sha(repository_.path(), ref);
  if (!commit) {
    // Nothing to push (for example a milestone with no coder branch yet).
    return {};
  }

  const std::string key = cf::idempotency_key(
      run_id, milestone_id, "push", cf::sha256_hex(branch + "|" + *commit));
  const auto existing = store_.find_operation_by_key(key);
  if (existing.has_value()) {
    return {};  // already intended (and possibly performed)
  }

  // Design section 10.4.6: run the pre-push checks on the exact commit before
  // any intent is recorded or any network call is made.
  auto findings =
      github::check_pre_push(repository_, branch, *commit, config_.pre_push);
  if (!findings) {
    return tl::make_unexpected(findings.error());
  }
  if (!findings->empty()) {
    std::string reason = "pre-push checks failed for " + branch + ":";
    for (const auto& finding : *findings) {
      reason += " " + finding.check + " (" + finding.message + ");";
    }
    return fail(github_error_codes::kPrePushRejected, reason);
  }

  auto remote_sha = repository_.remote_branch_sha(config_.remote, branch);
  const std::string old = remote_sha.has_value() ? *remote_sha : std::string();

  store::NewOperation intent;
  intent.idempotency_key = key;
  intent.milestone_id = std::string(milestone_id);
  intent.kind = "push";
  intent.input_json = Json{{"remote", config_.remote},
                           {"branch", branch},
                           {"commit", *commit}}
                          .dump();
  intent.expected_json = Json{{"old", old}, {"new", *commit}}.dump();
  const auto recorded = store_.record_intents(run_id, {intent}, now);
  if (!recorded && recorded.error().code != store::error_codes::kConflict) {
    return recorded;
  }
  return {};
}

Result<std::string> GithubFlow::build_pr_body(std::string_view run_id,
                                             const plan::Plan& plan,
                                             RunState run_state) const {
  auto summary = build_run_summary(store_, run_id, &plan);
  if (!summary) {
    return tl::make_unexpected(summary.error());
  }
  std::string body = "Automated run **" + std::string(run_id) + "** for plan `" +
                     plan.plan_id + "` (" + plan.product + ").\n\n";
  body += "Cost so far: $" + std::to_string(summary->usd) + ", " +
          std::to_string(summary->tokens) + " tokens.\n\n";
  body += render_run_summary_markdown(*summary);
  body += "\nRun state: " + std::string(to_string(run_state)) +
          ". Generated by the Coder Framework; a human reviews and merges.";
  if (!config_.report_path.empty()) {
    body += "\n\nFull report: `" + config_.report_path + "`";
  }
  return body;
}

Result<int64_t> GithubFlow::confirmed_pr_number(std::string_view run_id) const {
  auto operations = store_.list_operations(run_id, {store::op_state::kConfirmed});
  if (!operations) {
    return tl::make_unexpected(operations.error());
  }
  for (const auto& operation : *operations) {
    if (operation.kind != "pr_create") {
      continue;
    }
    const Json result = Json::parse(operation.result_json, nullptr, false);
    if (!result.is_discarded()) {
      const int64_t number = result.value("number", int64_t{0});
      if (number != 0) {
        return number;
      }
    }
  }
  return int64_t{0};
}

Result<store::UnixTime> GithubFlow::last_transition_at(
    std::string_view run_id, std::string_view to_state) const {
  auto transitions = store_.list_transitions(run_id, 0);
  if (!transitions) {
    return tl::make_unexpected(transitions.error());
  }
  store::UnixTime at = 0;
  for (const auto& transition : *transitions) {
    if (transition.to_state == to_state) {
      at = transition.at;
    }
  }
  return at;
}

Status GithubFlow::ensure_escalation(std::string_view run_id, store::UnixTime now) {
  auto escalated_at = last_transition_at(run_id, "Escalated");
  if (!escalated_at) {
    return tl::make_unexpected(escalated_at.error());
  }
  const std::string branch =
      "cf/" + std::string(run_id) + "/escalation/esc-" + std::to_string(*escalated_at);
  auto pushed = ensure_push(run_id, "", branch,
                            "cf/" + std::string(run_id) + "/integration", now);
  if (!pushed) {
    return pushed;
  }

  auto number = confirmed_pr_number(run_id);
  if (!number) {
    return tl::make_unexpected(number.error());
  }
  if (*number == 0) {
    return {};  // nothing to comment on yet
  }
  const std::string body =
      "Run `" + std::string(run_id) + "` escalated; work in progress is on `" +
      branch + "`. Bundle: runs/" + std::string(run_id) + "/escalations/esc-" +
      std::to_string(*escalated_at) + "/bundle.json";
  const std::string key = cf::idempotency_key(run_id, "", "comment",
                                              cf::sha256_hex(body));
  if (store_.find_operation_by_key(key).has_value()) {
    return {};
  }
  store::NewOperation intent;
  intent.idempotency_key = key;
  intent.kind = "comment";
  intent.input_json =
      Json{{"issue_number", *number}, {"body", body}}.dump();
  intent.expected_json = "{}";
  const auto recorded = store_.record_intents(run_id, {intent}, now);
  if (!recorded && recorded.error().code != store::error_codes::kConflict) {
    return recorded;
  }
  return {};
}

Status GithubFlow::ensure_abort(std::string_view run_id, const plan::Plan& plan,
                                RunState run_state, store::UnixTime now) {
  auto number = confirmed_pr_number(run_id);
  if (!number) {
    return tl::make_unexpected(number.error());
  }
  if (*number == 0) {
    return {};
  }
  auto body = build_pr_body(run_id, plan, run_state);
  if (!body) {
    return tl::make_unexpected(body.error());
  }
  const std::string key = cf::idempotency_key(
      run_id, "", "pr_update",
      cf::sha256_hex(std::to_string(*number) + "|" + *body + "|closed"));
  if (store_.find_operation_by_key(key).has_value()) {
    return {};
  }
  store::NewOperation intent;
  intent.idempotency_key = key;
  intent.kind = "pr_update";
  intent.input_json = Json{{"number", *number},
                           {"body", *body},
                           {"mark_ready", false},
                           {"state", "closed"}}
                          .dump();
  intent.expected_json = "{}";
  const auto recorded = store_.record_intents(run_id, {intent}, now);
  if (!recorded && recorded.error().code != store::error_codes::kConflict) {
    return recorded;
  }
  return {};
}

Status GithubFlow::ensure_pr(std::string_view run_id, const plan::Plan& plan,
                             RunState run_state, store::UnixTime now) {
  const std::string head = "cf/" + std::string(run_id) + "/integration";
  auto body = build_pr_body(run_id, plan, run_state);
  if (!body) {
    return tl::make_unexpected(body.error());
  }

  // What the confirmed operations already put on the pull request.
  auto operations = store_.list_operations(run_id, {store::op_state::kConfirmed});
  if (!operations) {
    return tl::make_unexpected(operations.error());
  }
  int64_t number = 0;
  std::string last_body;
  std::vector<std::string> last_labels;
  bool last_ready = false;
  bool last_request_codeowners = true;
  bool last_closed = false;
  store::UnixTime last_at = 0;
  for (const auto& operation : *operations) {
    if (operation.kind == "pr_create") {
      const Json result = Json::parse(operation.result_json, nullptr, false);
      if (!result.is_discarded()) {
        const int64_t parsed = result.value("number", int64_t{0});
        if (parsed != 0) {
          number = parsed;
        }
      }
    }
    if (operation.kind != "pr_create" && operation.kind != "pr_update") {
      continue;
    }
    if (operation.updated_at < last_at) {
      continue;
    }
    const Json input = Json::parse(operation.input_json, nullptr, false);
    if (input.is_discarded()) {
      continue;
    }
    last_at = operation.updated_at;
    last_body = input.value("body", "");
    last_labels = read_labels(input);
    last_ready = input.value("mark_ready", false);
    last_request_codeowners = input.value("request_codeowners", true);
    last_closed = input.value("state", "") == "closed";
  }

  if (number == 0) {
    const std::string key =
        cf::idempotency_key(run_id, "", "pr_create", cf::sha256_hex(head));
    if (store_.find_operation_by_key(key).has_value()) {
      return {};
    }
    const bool draft =
        config_.pr_draft_until_done && run_state != RunState::Done;
    store::NewOperation intent;
    intent.idempotency_key = key;
    intent.kind = "pr_create";
    intent.input_json =
        Json{{"base", config_.base_branch},
             {"head", head},
             {"title", config_.title_prefix + " " + std::string(run_id)},
             {"body", *body},
             {"draft", draft},
             {"labels", config_.pr_labels},
             {"request_codeowners", config_.pr_request_codeowners}}
            .dump();
    intent.expected_json = "{}";
    const auto recorded = store_.record_intents(run_id, {intent}, now);
    if (!recorded && recorded.error().code != store::error_codes::kConflict) {
      return recorded;
    }
    return {};
  }

  const bool mark_ready =
      config_.pr_draft_until_done && run_state == RunState::Done;
  if (last_body == *body && last_ready == mark_ready &&
      last_labels == config_.pr_labels &&
      last_request_codeowners == config_.pr_request_codeowners &&
      !last_closed) {
    return {};  // the pull request already shows the intended state
  }
  const std::string key = cf::idempotency_key(
      run_id, "", "pr_update",
      cf::sha256_hex(std::to_string(number) + "|" + *body +
                     (mark_ready ? "|ready" : "") + "|" +
                     join_labels(config_.pr_labels) + "|" +
                     (config_.pr_request_codeowners ? "reviewers" : "none")));
  if (store_.find_operation_by_key(key).has_value()) {
    return {};
  }
  store::NewOperation intent;
  intent.idempotency_key = key;
  intent.kind = "pr_update";
  intent.input_json =
      Json{{"number", number},
           {"body", *body},
           {"mark_ready", mark_ready},
           {"labels", config_.pr_labels},
           {"request_codeowners", config_.pr_request_codeowners}}
          .dump();
  intent.expected_json = "{}";
  const auto recorded = store_.record_intents(run_id, {intent}, now);
  if (!recorded && recorded.error().code != store::error_codes::kConflict) {
    return recorded;
  }
  return {};
}

Result<std::size_t> GithubFlow::sync(std::string_view run_id, const plan::Plan& plan,
                                     RunState run_state, uint64_t epoch,
                                     store::UnixTime now) {
  bool any_done = false;
  for (const auto& spec : plan.milestones) {
    const auto milestone = store_.get_milestone(run_id, spec.id);
    if (!milestone.has_value() || milestone->state != "Done") {
      continue;
    }
    any_done = true;
    // The milestone checkpoint branch, then the integration branch.
    auto ensured = ensure_push(run_id, spec.id, "cf/" + std::string(run_id) + "/" + spec.id,
                               "cf-local/" + std::string(run_id) + "/" + spec.id + "/coder",
                               now);
    if (!ensured) {
      return tl::make_unexpected(ensured.error());
    }
  }
  if (any_done) {
    auto integration =
        ensure_push(run_id, "", "cf/" + std::string(run_id) + "/integration",
                    "cf/" + std::string(run_id) + "/integration", now);
    if (!integration) {
      return tl::make_unexpected(integration.error());
    }
    auto pr = ensure_pr(run_id, plan, run_state, now);
    if (!pr) {
      return tl::make_unexpected(pr.error());
    }
  }
  if (run_state == RunState::Escalated) {
    auto escalated = ensure_escalation(run_id, now);
    if (!escalated) {
      return tl::make_unexpected(escalated.error());
    }
  } else if (run_state == RunState::Aborted) {
    auto aborted = ensure_abort(run_id, plan, run_state, now);
    if (!aborted) {
      return tl::make_unexpected(aborted.error());
    }
  }
  return dispatcher_.dispatch_pending(epoch, now);
}

